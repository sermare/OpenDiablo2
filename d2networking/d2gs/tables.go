// clientHandled lists in-game client ids that have a non-NULL handler in the
// table at 0x006e2010 (verified, game-net.md). Every other id in 0..0x66 has a
// NULL handler and the dispatcher rejects it.
var clientHandled = func() map[byte]bool {
	m := map[byte]bool{}
	for id := 1; id <= MaxClientID; id++ {
		m[byte(id)] = true
	}
	for _, id := range []byte{0x2b, 0x4a, 0x4e, 0x55, 0x56, 0x57, 0x5a, 0x5b, 0x5c, 0x64, 0x65} {
		delete(m, id)
	}
	return m
}()

